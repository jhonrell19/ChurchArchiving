const assert = require('node:assert/strict')
const { isAllowed } = require('../scripts/phase8_role_matrix.cjs')

for (const role of ['ADMIN','BURIAL_ADMIN','USER']) {
  assert.equal(isAllowed(role, 'GET', 'api/health'), true)
}
assert.equal(isAllowed('ADMIN','GET','api/archive/documents/baptismal'), true)
