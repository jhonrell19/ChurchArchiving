const assert = require('node:assert/strict')
const { isAllowed } = require('../scripts/phase8_role_matrix.cjs')

// Unified STAFF may handle all document categories, requests, and related cash.
for (const role of ['ADMIN', 'STAFF', 'BURIAL_ADMIN', 'USER'])
  assert.equal(isAllowed(role,'GET','api/health'), true)
for (const category of ['baptismal', 'confirmation', 'marriage', 'burial', 'land_agreement', 'ownership']) {
  assert.equal(isAllowed('STAFF', 'GET', 'api/archive/documents/' + category), true)
  assert.equal(isAllowed('ADMIN', 'GET', 'api/archive/documents/' + category), true)
}
assert.equal(isAllowed('STAFF','POST','api/archive/upload'),true)
assert.equal(isAllowed('ADMIN','POST','api/archive/upload'),false)
assert.equal(isAllowed('USER','POST','api/archive/upload'),false)
assert.equal(isAllowed('STAFF','PATCH','api/requests/42/select-record'),true)
assert.equal(isAllowed('ADMIN','PATCH','api/requests/42/select-record'),false)
assert.equal(isAllowed('STAFF','PATCH','api/requests/42/status'),true)
assert.equal(isAllowed('ADMIN','PATCH','api/requests/42/status'),false)
assert.equal(isAllowed('STAFF','POST','api/requests/42/release-document'),true)
assert.equal(isAllowed('ADMIN','POST','api/requests/42/release-document'),false)
assert.equal(isAllowed('STAFF','POST','api/requests/42/cash-receipt'),true)
assert.equal(isAllowed('ADMIN','POST','api/requests/42/cash-receipt'),false)
assert.equal(isAllowed('STAFF','GET','api/requests'),true)
assert.equal(isAllowed('USER','POST','api/requests'),true)
assert.equal(isAllowed('USER','GET','api/archive/documents'),false)
assert.equal(isAllowed('USER','PATCH','api/requests/42/status'),false)

// Read-only legacy deceased information, never cemetery sales/slot mutations.
assert.equal(isAllowed('STAFF','GET','api/cemetery/burials'),true)
assert.equal(isAllowed('STAFF','POST','api/cemetery/burials'),false)
assert.equal(isAllowed('STAFF','GET','api/cemetery/slots'),false)
assert.equal(isAllowed('BURIAL_ADMIN','GET','api/cemetery/slots'),true)

// Only Super Admin controls Mass, announcements, fees and audit/recovery.
assert.equal(isAllowed('STAFF','POST','api/masses'),false)
assert.equal(isAllowed('STAFF','PATCH','api/masses/3/transcription'),false)
assert.equal(isAllowed('STAFF','POST','api/announcements'),false)
assert.equal(isAllowed('STAFF','PATCH','api/requests/pricing'),false)
assert.equal(isAllowed('STAFF','GET','api/archive/audit-logs'),false)
assert.equal(isAllowed('STAFF','PATCH','api/archive/documents/5/delete'),false)
assert.equal(isAllowed('ADMIN','PATCH','api/archive/documents/5/delete'),true)
assert.equal(isAllowed('STAFF','POST','api/claims/9/review'),true)
assert.equal(isAllowed('ADMIN','POST','api/masses'),true)
assert.equal(isAllowed('ADMIN','GET','api/reports/members'),true)
assert.equal(isAllowed('USER','GET','api/reports/members'),false)
console.log('PASS: Super Admin, Church Staff, transitional burial and parishioner proxy gates')
