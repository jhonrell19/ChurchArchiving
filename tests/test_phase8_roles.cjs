assert.equal(isAllowed('ADMIN','POST','api/masses'),true)
assert.equal(isAllowed('ADMIN','GET','api/reports/members'),true)
assert.equal(isAllowed('USER','GET','api/reports/members'),false)
assert.equal(isAllowed('STAFF','GET','api/masses'),false)
